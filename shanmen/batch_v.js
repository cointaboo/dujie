后来每个月十五他都去。去了不进屋，坐在门槛上，让那妇人给他一碗汤。汤很淡，他喝得很慢。走的时候碗放在门槛上，摆得很正。

第十年，瘸腿的老兵死了。死的时候手里捏着一块铜腰牌，两个字：裴府。牌子磨得只剩个轮廓。

裴仲把腰牌收了，用布包起来，挂在西边那三间屋子的门框上。

「留着。」他说，「以后谁问起来，就说这儿姓裴。」

第十三年，马夫也死了。死的前一天他让人扶着去了西边的屋子，站在门口看了一会儿，说这屋子暖和。临死前他问，二少爷，咱们还回京城吗。

裴仲说，回。

马夫说，什么时候。

裴仲说，等你好了。

第十五年，那妇人的儿子来接她。她走的时候跪下来磕了三个头，磕完从怀里掏出一小包盐，放在灶台上，说这儿的盐成色不好，以后你们自己买。

她走到院门口又回头，说，二少爷，锅我刷干净了。

那三间屋子就空了。裴仲一个人住进去，自己做饭，做得很难吃，还是要做。炊烟每天两次，从西边升起来。

他后来在山上管宗卷，管了二十年。有人问他为什么不走，他说，屋里有人等着吃饭。

新来的弟子信了，还问他，一共几口人。他说，四口。

其实早没人了。

他每年清明都要摆三副碗。摆完自己坐在门槛上，等汤凉透了才收。

